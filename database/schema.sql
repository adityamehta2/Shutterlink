CREATE DATABASE IF NOT EXISTS shutterlink CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE shutterlink;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS bookings;
DROP TABLE IF EXISTS portfolio_items;
DROP TABLE IF EXISTS photographer_profiles;
DROP TABLE IF EXISTS users;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('client','photographer') NOT NULL DEFAULT 'client',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE photographer_profiles (
  id INT AUTO_INCREMENT PRIMARY KEY,
  user_id INT NOT NULL UNIQUE,
  headline VARCHAR(180) NOT NULL DEFAULT 'Freelance photographer',
  bio TEXT,
  city VARCHAR(100) NOT NULL,
  categories JSON NOT NULL,
  price_from DECIMAL(10,2) NOT NULL DEFAULT 2500,
  rating DECIMAL(3,2) NOT NULL DEFAULT 0,
  review_count INT NOT NULL DEFAULT 0,
  cover_image VARCHAR(500),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE portfolio_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  photographer_id INT NOT NULL,
  title VARCHAR(150) NOT NULL,
  image_url VARCHAR(500) NOT NULL,
  category VARCHAR(80) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (photographer_id) REFERENCES photographer_profiles(id) ON DELETE CASCADE
);

CREATE TABLE bookings (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  photographer_id INT NOT NULL,
  event_date DATE NOT NULL,
  event_time TIME NOT NULL DEFAULT '10:00:00',
  location VARCHAR(180) NOT NULL,
  category VARCHAR(80) NOT NULL,
  notes TEXT,
  total_amount DECIMAL(10,2) NOT NULL,
  status ENUM('pending','confirmed','completed','cancelled') NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (client_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (photographer_id) REFERENCES photographer_profiles(id) ON DELETE CASCADE,
  INDEX idx_booking_date (event_date),
  INDEX idx_booking_photographer_date (photographer_id, event_date)
);

CREATE TABLE payments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  booking_id INT NOT NULL UNIQUE,
  amount DECIMAL(10,2) NOT NULL,
  provider VARCHAR(40) NOT NULL DEFAULT 'DEMO',
  status ENUM('demo_paid','failed') NOT NULL DEFAULT 'demo_paid',
  reference_code VARCHAR(80) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE
);

